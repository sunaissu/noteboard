const {chromium,expect}=require('@playwright/test');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
 try {
  const page=await browser.newPage(); const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:5191/?mode=document');
  await page.waitForFunction(()=>window.documentBinding?.value.includes('Project notes'));
  await page.getByRole('button',{name:'Find & replace',exact:true}).click();
  await page.getByLabel('Find',{exact:true}).fill('plans');
  await page.getByLabel('Replace with',{exact:true}).fill('goals');
  await page.getByRole('button',{name:'Review replace all',exact:true}).click();
  await expect(page.getByRole('button',{name:'Apply',exact:true})).toBeVisible();
  await page.evaluate(()=>{const {text}=window.documentBinding; window.ydoc.transact(()=>text.insert(text.length,'\n\nPeer plans.'),'peer');});
  await expect(page.getByRole('button',{name:'Apply',exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'Review replace all',exact:true}).click();
  await page.getByRole('button',{name:'Apply',exact:true}).click();
  await page.waitForFunction(()=>window.documentBinding.value.includes('Peer goals.'));
  await page.evaluate(()=>window.documentBinding.history.undo());
  await page.waitForFunction(()=>window.documentBinding.value.includes('Peer plans.'));
  assert.ok((await page.evaluate(()=>window.documentBinding.value)).includes('about plans.'));
  await page.getByRole('button',{name:'Close panel',exact:true}).click();
  await page.evaluate(()=>window.documentBinding.onChange('<img src=x onerror="window.__attack=1">\n\n[x](javascript:alert(1))\n\n![image](mailto:x@y.test)'));
  const rich=page.locator('[contenteditable="true"]');
  await expect(rich).toContainText('<img src=x');
  assert.equal(await page.evaluate(()=>window.__attack),undefined);
  assert.equal(await rich.locator('[onerror],script,a[href^="javascript:"],img[src^="mailto:"]').count(),0);
  await page.goto('http://127.0.0.1:5191/?mode=board');
  await page.waitForFunction(()=>window.board?.getElements().length===4);
  await page.evaluate(()=>window.ydoc.getMap('noteboard-elements').set('bad','malformed'));
  assert.equal(await page.evaluate(()=>window.board.getElements().length),4);
  await page.evaluate(()=>window.ydoc.getMap('noteboard-elements').get('label').set('roughness',1));
  await page.evaluate(()=>window.ydoc.getMap('noteboard-elements').get('label').set('width',1e9));
  await page.waitForFunction(()=>window.board.getElements().find(e=>e.id==='label').width===1e9);
  await page.goto('http://127.0.0.1:5191/?mode=board&maxPixels=100000000&maxBytes=NaN');
  await page.waitForFunction(()=>window.board?.getElements().length===4);
  await page.evaluate(()=>{window.Image=class {naturalWidth=5000;naturalHeight=5000;set src(value){queueMicrotask(()=>this.onload?.());}};});
  const nextDialog=()=>new Promise(resolve=>page.once('dialog',async warning=>{const message=warning.message();await warning.dismiss();resolve(message);}));
  let dialog=nextDialog();
  await page.locator('input[accept="image/*"]').setInputFiles({name:'large.png',mimeType:'image/png',buffer:Buffer.from([1])});
  assert.match(await dialog,/pixel limit/);
  dialog=nextDialog();
  await page.locator('input[accept="image/*"]').setInputFiles({name:'oversized.png',mimeType:'image/png',buffer:Buffer.alloc(6*1024*1024)});
  assert.match(await dialog,/size limit/);
  assert.equal(await page.evaluate(()=>window.board.getElements().length),4);
  assert.deepEqual(errors,[]);
  console.log('Stale replace confirmation, collaborative undo, inert hostile markup, peer quarantine and huge rough shapes passed');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
